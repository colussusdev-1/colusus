import applicationService from "./application.service.js";

/*
============================================================
CREATE APPLICATION
============================================================
|
| Creates a new application from the selected opportunity.
|
| The application service generates the permanent:
|
| applicationReference
|
| Example:
|
| COL-68B3A91F4D2C8E7A1B5C9032
|
| This reference is created once and never changes.
|
============================================================
*/

export const createApplication = async (req, res, next) => {
  try {
    /*
    ----------------------------------------------------------
    AUTHENTICATED CLIENT
    ----------------------------------------------------------
    */

    const userId = req.user?.id;

    if (!userId) {
      return res.status(401).json({
        success: false,

        message: "Authenticated user not found.",
      });
    }

    /*
    ----------------------------------------------------------
    CREATE APPLICATION
    ----------------------------------------------------------
    */

    const result = await applicationService.createApplication({
      /*
      --------------------------------------------------------
      CLIENT
      --------------------------------------------------------
      */

      user: userId,

      /*
      --------------------------------------------------------
      OPPORTUNITY
      --------------------------------------------------------
      */

      opportunity: req.body.opportunity,

      /*
      --------------------------------------------------------
      DESTINATION
      --------------------------------------------------------
      */

      destinationCountry: req.body.destinationCountry,

      /*
      --------------------------------------------------------
      PRIORITY
      --------------------------------------------------------
      */

      priority: req.body.priority,

      /*
      --------------------------------------------------------
      CLIENT NOTES
      --------------------------------------------------------
      */

      notes: req.body.notes,
    });

    /*
    ----------------------------------------------------------
    APPLICATION
    ----------------------------------------------------------
    */

    const application = result?.application;

    /*
    ----------------------------------------------------------
    SAFETY CHECK
    ----------------------------------------------------------
    */

    if (!application) {
      return res.status(500).json({
        success: false,

        message: "Application could not be created.",
      });
    }

    /*
    ----------------------------------------------------------
    PERMANENT APPLICATION REFERENCE
    ----------------------------------------------------------
    |
    | The reference is generated by the service and stored
    | permanently on the Application document.
    |
    | We expose it directly in the API response so the
    | frontend can immediately display it without needing
    | another request.
    |
    ----------------------------------------------------------
    */

    const applicationReference = application.applicationReference || null;

    /*
    ----------------------------------------------------------
    SUCCESS
    ----------------------------------------------------------
    */

    return res.status(201).json({
      success: true,

      message: "Application draft created successfully",

      data: {
        /*
        ------------------------------------------------------
        APPLICATION
        ------------------------------------------------------
        */

        application,

        /*
        ------------------------------------------------------
        PERMANENT APPLICATION REFERENCE
        ------------------------------------------------------
        */

        applicationReference,

        /*
        ------------------------------------------------------
        PROFILE STATUS
        ------------------------------------------------------
        */

        profileComplete: Boolean(result?.profileComplete),

        requiresProfileCompletion: Boolean(result?.requiresProfileCompletion),

        missingProfileFields: Array.isArray(result?.missingProfileFields)
          ? result.missingProfileFields
          : [],
      },
    });
  } catch (error) {
    next(error);
  }
};

/*
============================================================
GET USER APPLICATIONS
============================================================
|
| GET /api/v1/applications
|
| Returns every application belonging to the authenticated
| client.
|
| Every application includes its permanent:
|
| applicationReference
|
============================================================
*/

export const getApplications = async (req, res, next) => {
  try {
    /*
    ----------------------------------------------------------
    AUTHENTICATED CLIENT
    ----------------------------------------------------------
    */

    const userId = req.user?.id;

    if (!userId) {
      return res.status(401).json({
        success: false,

        message: "Authenticated user not found.",
      });
    }

    /*
    ----------------------------------------------------------
    GET APPLICATIONS
    ----------------------------------------------------------
    */

    const applications = await applicationService.getUserApplications(userId);

    /*
    ----------------------------------------------------------
    SUCCESS
    ----------------------------------------------------------
    */

    return res.status(200).json({
      success: true,

      data: applications,
    });
  } catch (error) {
    next(error);
  }
};

/*
============================================================
GET SINGLE APPLICATION
============================================================
|
| GET /api/v1/applications/:id
|
| The :id remains the MongoDB identifier used internally
| for routing.
|
| The returned application also contains:
|
| applicationReference
|
| which is the permanent human-facing colossus ID.
|
============================================================
*/

export const getApplication = async (req, res, next) => {
  try {
    /*
    ----------------------------------------------------------
    APPLICATION ID
    ----------------------------------------------------------
    */

    const applicationId = req.params.id;

    if (!applicationId) {
      return res.status(400).json({
        success: false,

        message: "Application ID is required.",
      });
    }

    /*
    ----------------------------------------------------------
    AUTHENTICATED CLIENT
    ----------------------------------------------------------
    */

    const userId = req.user?.id;

    if (!userId) {
      return res.status(401).json({
        success: false,

        message: "Authenticated user not found.",
      });
    }

    /*
    ----------------------------------------------------------
    GET APPLICATION
    ----------------------------------------------------------
    */

    const application = await applicationService.getApplicationById(
      applicationId,
      userId,
    );

    /*
    ----------------------------------------------------------
    APPLICATION NOT FOUND
    ----------------------------------------------------------
    */

    if (!application) {
      return res.status(404).json({
        success: false,

        message: "Application not found",
      });
    }

    /*
    ----------------------------------------------------------
    SUCCESS
    ----------------------------------------------------------
    */

    return res.status(200).json({
      success: true,

      data: application,
    });
  } catch (error) {
    next(error);
  }
};

/*
============================================================
UPDATE APPLICATION JOURNEY
============================================================
|
| PATCH /api/v1/applications/:id
|
| Client-owned updates only.
|
| Supported:
|
| - currentStep
| - currentStepIndex
| - personalInformation
| - answers
| - notes
|
| The client cannot directly control administrative statuses.
|
============================================================
*/

export const updateApplication = async (req, res, next) => {
  try {
    /*
    ----------------------------------------------------------
    APPLICATION ID
    ----------------------------------------------------------
    */

    const applicationId = req.params.id;

    if (!applicationId) {
      return res.status(400).json({
        success: false,

        message: "Application ID is required.",
      });
    }

    /*
    ----------------------------------------------------------
    AUTHENTICATED CLIENT
    ----------------------------------------------------------
    */

    const userId = req.user?.id;

    if (!userId) {
      return res.status(401).json({
        success: false,

        message: "Authenticated user not found.",
      });
    }

    /*
    ----------------------------------------------------------
    UPDATE APPLICATION
    ----------------------------------------------------------
    |
    | IMPORTANT:
    |
    | We deliberately do NOT pass:
    |
    | - applicationReference
    | | - status
    | | - assignedTo
    | | - lastUpdatedBy
    |
    | These are backend-controlled fields.
    |
    ----------------------------------------------------------
    */

    const application = await applicationService.updateApplication(
      applicationId,

      userId,

      {
        /*
          ----------------------------------------------------
          JOURNEY
          ----------------------------------------------------
          */

        currentStep: req.body.currentStep,

        currentStepIndex: req.body.currentStepIndex,

        /*
          ----------------------------------------------------
          PERSONAL INFORMATION
          ----------------------------------------------------
          */

        personalInformation: req.body.personalInformation,

        /*
          ----------------------------------------------------
          APPLICATION ANSWERS
          ----------------------------------------------------
          */

        answers: req.body.answers,

        /*
          ----------------------------------------------------
          CLIENT NOTES
          ----------------------------------------------------
          */

        notes: req.body.notes,
      },
    );

    /*
    ----------------------------------------------------------
    APPLICATION NOT FOUND
    ----------------------------------------------------------
    */

    if (!application) {
      return res.status(404).json({
        success: false,

        message: "Application not found",
      });
    }

    /*
    ----------------------------------------------------------
    SUCCESS
    ----------------------------------------------------------
    |
    | Return the complete updated application.
    |
    | This allows the frontend to immediately replace its
    | local application state without a page reload.
    |
    ----------------------------------------------------------
    */

    return res.status(200).json({
      success: true,

      message: "Application progress updated successfully",

      data: application,
    });
  } catch (error) {
    next(error);
  }
};

/*
============================================================
EXPORT
============================================================
*/

export default {
  /*
  | Application creation
  */

  createApplication,

  /*
  | Application retrieval
  */

  getApplications,

  getApplication,

  /*
  | Application updates
  */

  updateApplication,
};
