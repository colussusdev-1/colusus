import nodemailer from "nodemailer";

/* -------------------------------------------------------------------------- */
/* SMTP CONFIGURATION                                                         */
/* -------------------------------------------------------------------------- */

let transporter = null;

const getTransporter = () => {
  if (transporter) {
    return transporter;
  }

  const {
    SMTP_HOST,
    SMTP_PORT = "587",
    SMTP_SECURE = "false",
    SMTP_USER,
    SMTP_PASS,
  } = process.env;

  if (!SMTP_HOST || !SMTP_USER || !SMTP_PASS) {
    throw new Error(
      "SMTP configuration is incomplete. Check SMTP_HOST, SMTP_USER and SMTP_PASS.",
    );
  }

  transporter = nodemailer.createTransport({
    host: SMTP_HOST,
    port: Number(SMTP_PORT),
    secure: String(SMTP_SECURE).toLowerCase() === "true",

    auth: {
      user: SMTP_USER,
      pass: SMTP_PASS,
    },
  });

  return transporter;
};

/* -------------------------------------------------------------------------- */
/* HTML ESCAPING                                                              */
/* -------------------------------------------------------------------------- */

const escapeHtml = (value = "") => {
  return String(value).replace(/[&<>"']/g, (character) => {
    const entities = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;",
    };

    return entities[character];
  });
};

/* -------------------------------------------------------------------------- */
/* ADMIN NOTIFICATION EMAIL                                                   */
/* -------------------------------------------------------------------------- */

const sendAdminNotificationEmail = async (notification) => {
  const recipient =
    process.env.ADMIN_NOTIFICATION_EMAIL ||
    "admin@colossusmigration.com";

  const sender =
    process.env.MAIL_FROM ||
    process.env.SMTP_USER;

  if (!sender) {
    throw new Error(
      "MAIL_FROM or SMTP_USER must be configured.",
    );
  }

  const mailTransporter = getTransporter();

  const title = escapeHtml(notification.title);
  const message = escapeHtml(notification.message);

  const category = escapeHtml(notification.category);
  const type = escapeHtml(notification.type);
  const priority = escapeHtml(notification.priority || "NORMAL");

  const createdAt = new Date().toLocaleString("en-NG", {
    dateStyle: "medium",
    timeStyle: "short",
    timeZone: "Africa/Lagos",
  });

  const subject = `[Colossus ${notification.category}] ${notification.title}`;

  const text = [
    "A new notification has been generated in Colossus Migration & Tours.",
    "",
    `Title: ${notification.title}`,
    `Message: ${notification.message}`,
    `Category: ${notification.category}`,
    `Type: ${notification.type}`,
    `Priority: ${notification.priority || "NORMAL"}`,
    `Time: ${createdAt}`,
  ].join("\n");

  const html = `
    <!DOCTYPE html>
    <html lang="en">
      <head>
        <meta charset="UTF-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1.0" />
        <title>${title}</title>
      </head>

      <body style="
        margin: 0;
        padding: 24px;
        background-color: #f3f4f6;
        font-family: Arial, Helvetica, sans-serif;
        color: #1f2937;
      ">
        <div style="
          max-width: 600px;
          margin: 0 auto;
          background: #ffffff;
          border-radius: 12px;
          overflow: hidden;
          border: 1px solid #e5e7eb;
        ">
          <div style="
            padding: 24px;
            background: #10243a;
            color: #ffffff;
          ">
            <h1 style="
              margin: 0;
              font-size: 22px;
            ">
              Colossus Migration &amp; Tours
            </h1>

            <p style="
              margin: 8px 0 0;
              color: #d1d5db;
              font-size: 14px;
            ">
              Admin Notification
            </p>
          </div>

          <div style="padding: 24px;">
            <p style="
              margin-top: 0;
              font-size: 14px;
              color: #6b7280;
            ">
              A new notification has been generated by the platform.
            </p>

            <h2 style="
              margin-bottom: 12px;
              font-size: 20px;
              color: #111827;
            ">
              ${title}
            </h2>

            <p style="
              font-size: 15px;
              line-height: 1.7;
              white-space: pre-wrap;
            ">
              ${message}
            </p>

            <div style="
              margin-top: 24px;
              padding: 16px;
              background: #f9fafb;
              border-radius: 8px;
              border: 1px solid #e5e7eb;
            ">
              <p style="margin: 0 0 8px;">
                <strong>Category:</strong> ${category}
              </p>

              <p style="margin: 0 0 8px;">
                <strong>Event:</strong> ${type}
              </p>

              <p style="margin: 0 0 8px;">
                <strong>Priority:</strong> ${priority}
              </p>

              <p style="margin: 0;">
                <strong>Time:</strong> ${escapeHtml(createdAt)}
              </p>
            </div>

            <p style="
              margin: 24px 0 0;
              font-size: 12px;
              color: #6b7280;
            ">
              This is an automated notification from the
              Colossus Migration &amp; Tours platform.
            </p>
          </div>
        </div>
      </body>
    </html>
  `;

  const result = await mailTransporter.sendMail({
    from: sender,
    to: recipient,
    subject,
    text,
    html,
  });

  console.log(
    `[Notification Email] Admin email sent for "${notification.type}". Message ID: ${result.messageId}`,
  );

  return result;
};

/* -------------------------------------------------------------------------- */
/* SAFE EMAIL DELIVERY                                                        */
/* -------------------------------------------------------------------------- */

/**
 * Email failures must never break the existing notification workflow.
 */
const safelySendAdminNotificationEmail = async (notification) => {
  try {
    return await sendAdminNotificationEmail(notification);
  } catch (error) {
    console.error(
      "[Notification Email] Failed to send admin notification:",
      error.message,
    );

    return null;
  }
};

/* -------------------------------------------------------------------------- */
/* EXPORTS                                                                    */
/* -------------------------------------------------------------------------- */

export {
  sendAdminNotificationEmail,
  safelySendAdminNotificationEmail,
};