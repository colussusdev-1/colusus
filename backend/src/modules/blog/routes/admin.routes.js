import express from "express";

import authenticate from "../../../middleware/auth.middleware.js";
import { allowRoles } from "../../../middleware/role.middleware.js";

import {
  createPost,
  getPosts,
  getPost,
  updatePost,
  deletePost,
  publishPost,
  schedulePost,
  unpublishPost,
  toggleFeatured,
} from "../controllers/admin.controller.js";

import {
  getComments,
  createEditorialComment,
  updateComment,
  deleteComment,
  approveComment,
  rejectComment,
  scheduleComment,
  togglePinComment,
} from "../controllers/comment.controller.js";

const router = express.Router();

/*
|--------------------------------------------------------------------------
| BLOG ADMIN AUTHENTICATION
|--------------------------------------------------------------------------
|
| All routes in this module require:
|
| 1. A valid JWT
| 2. ADMIN role
|
| Public Blog routes remain completely separate.
|
|--------------------------------------------------------------------------
*/

router.use(authenticate, allowRoles("ADMIN"));

/*
|--------------------------------------------------------------------------
| BLOG POSTS
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| CREATE POST
|--------------------------------------------------------------------------
|
| POST /api/v1/admin/blog
|
|--------------------------------------------------------------------------
*/

router.post("/", createPost);

/*
|--------------------------------------------------------------------------
| GET ALL POSTS
|--------------------------------------------------------------------------
|
| GET /api/v1/admin/blog
|
|--------------------------------------------------------------------------
*/

router.get("/", getPosts);

/*
|--------------------------------------------------------------------------
| COMMENTS
|--------------------------------------------------------------------------
|
| These routes MUST come before:
|
| /:id
|
| so "/comments" is not interpreted as a blog post ID.
|
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| GET COMMENTS
|--------------------------------------------------------------------------
|
| GET /api/v1/admin/blog/comments
|
|--------------------------------------------------------------------------
*/

router.get("/comments", getComments);

/*
|--------------------------------------------------------------------------
| CREATE EDITORIAL COMMENT
|--------------------------------------------------------------------------
|
| POST /api/v1/admin/blog/:id/comments
|
|--------------------------------------------------------------------------
*/

router.post("/:id/comments", createEditorialComment);

/*
|--------------------------------------------------------------------------
| UPDATE COMMENT
|--------------------------------------------------------------------------
|
| PATCH /api/v1/admin/blog/comments/:commentId
|
|--------------------------------------------------------------------------
*/

router.patch("/comments/:commentId", updateComment);

/*
|--------------------------------------------------------------------------
| DELETE COMMENT
|--------------------------------------------------------------------------
|
| DELETE /api/v1/admin/blog/comments/:commentId
|
|--------------------------------------------------------------------------
*/

router.delete("/comments/:commentId", deleteComment);

/*
|--------------------------------------------------------------------------
| APPROVE COMMENT
|--------------------------------------------------------------------------
|
| POST /api/v1/admin/blog/comments/:commentId/approve
|
|--------------------------------------------------------------------------
*/

router.post("/comments/:commentId/approve", approveComment);

/*
|--------------------------------------------------------------------------
| REJECT COMMENT
|--------------------------------------------------------------------------
|
| POST /api/v1/admin/blog/comments/:commentId/reject
|
|--------------------------------------------------------------------------
*/

router.post("/comments/:commentId/reject", rejectComment);

/*
|--------------------------------------------------------------------------
| SCHEDULE COMMENT
|--------------------------------------------------------------------------
|
| POST /api/v1/admin/blog/comments/:commentId/schedule
|
|--------------------------------------------------------------------------
*/

router.post("/comments/:commentId/schedule", scheduleComment);

/*
|--------------------------------------------------------------------------
| PIN / UNPIN COMMENT
|--------------------------------------------------------------------------
|
| POST /api/v1/admin/blog/comments/:commentId/pin
|
|--------------------------------------------------------------------------
*/

router.post("/comments/:commentId/pin", togglePinComment);

/*
|--------------------------------------------------------------------------
| SINGLE POST
|--------------------------------------------------------------------------
|
| These routes come after the explicit /comments routes.
|
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| GET SINGLE POST
|--------------------------------------------------------------------------
|
| GET /api/v1/admin/blog/:id
|
|--------------------------------------------------------------------------
*/

router.get("/:id", getPost);

/*
|--------------------------------------------------------------------------
| UPDATE POST
|--------------------------------------------------------------------------
|
| PATCH /api/v1/admin/blog/:id
|
|--------------------------------------------------------------------------
*/

router.patch("/:id", updatePost);

/*
|--------------------------------------------------------------------------
| DELETE POST
|--------------------------------------------------------------------------
|
| DELETE /api/v1/admin/blog/:id
|
|--------------------------------------------------------------------------
*/

router.delete("/:id", deletePost);

/*
|--------------------------------------------------------------------------
| PUBLISH POST
|--------------------------------------------------------------------------
|
| POST /api/v1/admin/blog/:id/publish
|
|--------------------------------------------------------------------------
*/

router.post("/:id/publish", publishPost);

/*
|--------------------------------------------------------------------------
| SCHEDULE POST
|--------------------------------------------------------------------------
|
| POST /api/v1/admin/blog/:id/schedule
|
|--------------------------------------------------------------------------
*/

router.post("/:id/schedule", schedulePost);

/*
|--------------------------------------------------------------------------
| UNPUBLISH POST
|--------------------------------------------------------------------------
|
| POST /api/v1/admin/blog/:id/unpublish
|
|--------------------------------------------------------------------------
*/

router.post("/:id/unpublish", unpublishPost);

/*
|--------------------------------------------------------------------------
| FEATURE / UNFEATURE POST
|--------------------------------------------------------------------------
|
| PATCH /api/v1/admin/blog/:id/featured
|
|--------------------------------------------------------------------------
*/

router.patch("/:id/featured", toggleFeatured);

export default router;
