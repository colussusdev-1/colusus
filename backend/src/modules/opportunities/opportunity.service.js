import Opportunity from "./opportunity.model.js";

/*
|--------------------------------------------------------------------------
| GET ALL OPPORTUNITIES
|--------------------------------------------------------------------------
*/

const getAllOpportunities = async (filters = {}) => {
  const query = {
    active: true,
  };

  if (filters.country) {
    query.countrySlug = filters.country;
  }

  if (filters.category) {
    query.category = filters.category;
  }

  if (filters.featured !== undefined) {
    query.featured = filters.featured;
  }

  return Opportunity.find(query).sort({
    createdAt: -1,
  });
};

/*
|--------------------------------------------------------------------------
| GET SINGLE OPPORTUNITY
|--------------------------------------------------------------------------
*/

const getOpportunityBySlug = async (countrySlug, opportunitySlug) => {
  return Opportunity.findOne({
    countrySlug,

    slug: opportunitySlug,

    active: true,
  });
};

/*
|--------------------------------------------------------------------------
| GET OPPORTUNITY BY ID
|--------------------------------------------------------------------------
*/

const getOpportunityById = async (id) => {
  return Opportunity.findOne({
    _id: id,

    active: true,
  });
};

/*
|--------------------------------------------------------------------------
| GET COUNTRIES
|--------------------------------------------------------------------------
|
| Countries are derived from the opportunities collection.
|
| Only active opportunities are exposed publicly.
|
| Multiple opportunities can belong to the same country, so we group
| them by countrySlug and use the country-level fields from the
| first opportunity.
|
|--------------------------------------------------------------------------
*/

const getCountries = async () => {
  return Opportunity.aggregate([
    /*
    |--------------------------------------------------------------------------
    | ACTIVE OPPORTUNITIES ONLY
    |--------------------------------------------------------------------------
    */

    {
      $match: {
        active: true,
      },
    },

    /*
    |--------------------------------------------------------------------------
    | PRIORITIZE FEATURED / RECENT RECORDS
    |--------------------------------------------------------------------------
    |
    | This ensures that when a country has multiple opportunities,
    | the featured opportunity's country information is preferred.
    |
    |--------------------------------------------------------------------------
    */

    {
      $sort: {
        featured: -1,
        createdAt: -1,
      },
    },

    /*
    |--------------------------------------------------------------------------
    | GROUP BY COUNTRY
    |--------------------------------------------------------------------------
    */

    {
      $group: {
        _id: "$countrySlug",

        /*
        |--------------------------------------------------------------------------
        | COUNTRY SLUG
        |--------------------------------------------------------------------------
        |
        | CountryCard uses this for:
        |
        | /opportunities/:slug
        |
        |--------------------------------------------------------------------------
        */

        slug: {
          $first: "$countrySlug",
        },

        /*
        |--------------------------------------------------------------------------
        | COUNTRY NAME
        |--------------------------------------------------------------------------
        */

        name: {
          $first: "$countryName",
        },

        /*
        |--------------------------------------------------------------------------
        | COUNTRY FLAG
        |--------------------------------------------------------------------------
        */

        flag: {
          $first: "$countryFlag",
        },

        /*
        |--------------------------------------------------------------------------
        | COUNTRY IMAGE
        |--------------------------------------------------------------------------
        */

        image: {
          $first: "$countryImage",
        },

        /*
        |--------------------------------------------------------------------------
        | APPLICANTS
        |--------------------------------------------------------------------------
        */

        applicants: {
          $first: "$applicants",
        },

        /*
        |--------------------------------------------------------------------------
        | COUNTRY CATEGORIES
        |--------------------------------------------------------------------------
        |
        | Example:
        |
        | ["popular", "affordable"]
        |
        |--------------------------------------------------------------------------
        */

        category: {
          $first: "$countryCategories",
        },

        /*
        |--------------------------------------------------------------------------
        | VISA
        |--------------------------------------------------------------------------
        */

        visa: {
          $first: "$countryVisa",
        },

        /*
        |--------------------------------------------------------------------------
        | DURATION
        |--------------------------------------------------------------------------
        */

        duration: {
          $first: "$countryDuration",
        },

        /*
        |--------------------------------------------------------------------------
        | PROCESSING TIME
        |--------------------------------------------------------------------------
        */

        processingTime: {
          $first: "$countryProcessingTime",
        },

        /*
        |--------------------------------------------------------------------------
        | OPPORTUNITY SCORE
        |--------------------------------------------------------------------------
        */

        opportunityScore: {
          $first: "$opportunityScore",
        },

        /*
        |--------------------------------------------------------------------------
        | SUCCESS RATE
        |--------------------------------------------------------------------------
        */

        successRate: {
          $first: "$successRate",
        },

        /*
        |--------------------------------------------------------------------------
        | FEATURED
        |--------------------------------------------------------------------------
        */

        featured: {
          $first: "$featured",
        },

        /*
        |--------------------------------------------------------------------------
        | COUNTRY DESCRIPTION
        |--------------------------------------------------------------------------
        */

        description: {
          $first: "$countryDescription",
        },
      },
    },

    /*
    |--------------------------------------------------------------------------
    | FINAL COUNTRY SORT
    |--------------------------------------------------------------------------
    */

    {
      $sort: {
        name: 1,
      },
    },
  ]);
};

/*
|--------------------------------------------------------------------------
| EXPORT
|--------------------------------------------------------------------------
*/

export default {
  getAllOpportunities,

  getOpportunityBySlug,

  getOpportunityById,

  getCountries,
};
